import { describe, expect, it } from "vitest";
import { mentionsRu, replaceKo, replaceRu } from "./replace";

describe("замена имени в русском тексте", () => {
  it("целые слова, части других слов не задевает", () => {
    const t = "Ким пришёл. Кимчи было острым, а Кимура — японец. «Ким!» — крикнула мама.";
    const r = replaceRu(t, "Ким", "Кім");
    expect(r.text).toBe("Кім пришёл. Кимчи было острым, а Кимура — японец. «Кім!» — крикнула мама.");
    expect(r.count).toBe(2);
    expect(replaceRu("Лена и Леночка, Ленин", "Лена", "Лина").text).toBe("Лина и Леночка, Ленин");
  });

  it("падежи при одинаковом окончании", () => {
    const t = "У Ерлана был ЗИЛ. С Ерланом мы дружили. Ерлану я писал. Ерлан.";
    expect(replaceRu(t, "Ерлан", "Ерлин").text).toBe("У Ерлина был ЗИЛ. С Ерлином мы дружили. Ерлину я писал. Ерлин.");
    expect(replaceRu("в Уштабе, из Уштабе", "Уштабе", "Уштобе").text).toBe("в Уштобе, из Уштобе");
  });

  it("«Вова» → «Володя»: формы по таблице а ↔ я, основа без окончания не трогается", () => {
    const t = "Вова пришёл. У Вовы, к Вове, с Вовой, про Вову. Вов — это другое.";
    const r = replaceRu(t, "Вова", "Володя");
    expect(r.text).toBe("Володя пришёл. У Володи, к Володе, с Володей, про Володю. Вов — это другое.");
    expect(r.count).toBe(5);
  });

  it("разные окончания без таблицы — только точная форма", () => {
    expect(replaceRu("Аня и Ани, Ане", "Аня", "Анна").text).toBe("Анна и Ани, Ане"); // основа короче 3 букв
    expect(replaceRu("Саша и Саши", "Саша", "Александр").text).toBe("Александр и Саши");
  });

  it("регистр первой буквы как в тексте; многословные — точная фраза", () => {
    expect(replaceRu("ели кукси и Кукси", "кукси", "куксу").text).toBe("ели куксу и Куксу");
    expect(replaceRu("ездили на Иссык-Куль, у Иссык-Куля", "Иссык-Куль", "Ыссык-Көл").text).toBe("ездили на Ыссык-Көл, у Иссык-Куля");
    expect(replaceRu("пришла апа Сауле", "апа Сауле", "апа Сәуле").text).toBe("пришла апа Сәуле");
  });

  it("пусто и без изменений", () => {
    expect(replaceRu(null, "Ким", "Кім")).toEqual({ text: "", count: 0 });
    expect(replaceRu("Ким", "Ким", "Ким").count).toBe(0);
  });

  it("упоминание — с падежами", () => {
    expect(mentionsRu("Мы ждали Ерлана", "Ерлан")).toBe(true);
    expect(mentionsRu("Кимчи", "Ким")).toBe(false);
    expect(mentionsRu("к Вове", "Вова")).toBe(true);
  });
});

describe("замена имени в корейском тексте", () => {
  it("с частицами, без задевания других слов", () => {
    const t = "보바가 왔다. 보바의 집, 보바에게. 보바리 부인.";
    const r = replaceKo(t, "보바", "볼로댜");
    expect(r.text).toBe("볼로댜가 왔다. 볼로댜의 집, 볼로댜에게. 보바리 부인.");
    expect(r.count).toBe(3);
  });

  it("одна буква и пусто — не трогаем", () => {
    expect(replaceKo("김치 김", "김", "킴").count).toBe(0);
    expect(replaceKo(null, "보바", "볼로댜").text).toBe("");
  });
});
